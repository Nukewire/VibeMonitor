def create_setup_app(config_path: Path | None = None) -> Flask:
    """Setup-wizard Flask app. `config_path` is the target config.toml (injectable
    for tests); defaults to bridge/config.toml."""
    app = Flask(__name__)
    app.config["CONFIG_PATH"] = Path(config_path) if config_path else DEFAULT_CONFIG_PATH

    @app.get("/")
    def index():
        html = _STATIC_DIR / "setup.html"
        if not html.exists():
            return Response("setup.html not found", status=404, mimetype="text/plain")
        return Response(html.read_text(encoding="utf-8"), mimetype="text/html")

    @app.get("/api/defaults")
    def defaults():
        target = Path(app.config["CONFIG_PATH"])
        return jsonify({
            "token": secrets.token_urlsafe(12),
            "local_ip": local_ip(),
            "port": 5151,
            "ntfy_topic": _suggest_ntfy_topic(),
            "config_exists": target.exists(),
            "config_path": str(target),
        })

    @app.post("/api/test-openrouter")
    def test_openrouter():
        data = request.get_json(silent=True) or {}
        api_key = (data.get("api_key") or "").strip()
        model = (data.get("model") or "google/gemma-4-31b-it:free").strip()
        if not api_key:
            return jsonify({"ok": False, "error": "missing api_key"})
        result = summarizer.summarize("hello", api_key=api_key, model=model)
        return jsonify({"ok": result is not None})

    @app.post("/api/test-ntfy")
    def test_ntfy():
        data = request.get_json(silent=True) or {}
        ntfy_url = (data.get("ntfy_url") or "").strip()
        if not ntfy_url:
            return jsonify({"ok": False, "error": "missing ntfy_url"})
        ok = PushNotifier(provider="ntfy", ntfy_url=ntfy_url).send(
            "VibeMonitor", "Test push from setup"
        )
        return jsonify({"ok": bool(ok)})

    @app.post("/api/install-hooks")
    def install_hooks_endpoint():
        data = request.get_json(silent=True) or {}
        token = (data.get("token") or "").strip()
        url = (data.get("url") or "http://localhost:5151/hook").strip()
        if not token:
            return jsonify({"ok": False, "message": "missing token"})
        return jsonify(_install_hooks_into_settings(token, url))

    @app.post("/api/save")
    def save():
        form = request.get_json(silent=True) or {}
        target = Path(app.config["CONFIG_PATH"])
        toml_text = build_toml(form)
        try:
            target.parent.mkdir(parents=True, exist_ok=True)
            if target.exists():
                backup = target.with_suffix(".toml.bak")
                shutil.copy(target, backup)
            target.write_text(toml_text, encoding="utf-8")
        except Exception as e:
            return jsonify({"ok": False, "error": str(e)}), 500

        ip = (form.get("local_ip") or local_ip()).strip() or local_ip()
        try:
            port = int(form.get("port", 5151))
        except (TypeError, ValueError):
            port = 5151
        token = (form.get("token") or "").strip()
        next_steps = [
            f"Start the bridge:  python -m vibemonitor.main config.toml  "
            f"(serves http://{ip}:{port})",
            f"Provision the device with host={ip} port={port} token=<your token>",
            "Open the dashboard at http://%s:%d/ and paste the token once." % (ip, port),
        ]
        return jsonify({
            "ok": True,
            "path": str(target),
            "ha": ha_snippets(ip, port, token),
            "next_steps": next_steps,
        })

    return app


def main(argv: list[str] | None = None) -> int:
    app = create_setup_app()
    host, port = "127.0.0.1", 5152
    url = f"http://{host}:{port}/"
    print(f"VibeMonitor setup wizard: {url}")
    print("Opening your browser... (Ctrl+C to quit)")
    try:
        webbrowser.open(url)
    except Exception:
        pass
    app.run(host=host, port=port, debug=False, use_reloader=False)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
