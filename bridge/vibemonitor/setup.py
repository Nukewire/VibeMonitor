def local_ip() -> str:
    """Best-effort LAN IP. Opens a UDP socket toward a public address (no packets
    actually sent) and reads the chosen local interface. Falls back to 127.0.0.1.
    Never raises."""
    s = None
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(("8.8.8.8", 80))
        ip = s.getsockname()[0]
        return ip or "127.0.0.1"
    except Exception:
        return "127.0.0.1"
    finally:
        if s is not None:
            try:
                s.close()
            except Exception:
                pass


def _suggest_ntfy_topic() -> str:
    return f"vibemon-{secrets.choice(_TOPIC_WORDS)}-{secrets.token_hex(2)}"


def ha_snippets(ip: str, port: int, token: str) -> dict:
    """Ready-to-paste Home Assistant YAML, pre-filled with ip/port/token.

    Returns {"sensor": <rest+template yaml>, "automation": <webhook yaml>}.
    Mirrors the contract in README's Home Assistant section.
    """
    resource = f"http://{ip}:{port}/ha"
    sensor = f"""# configuration.yaml — poll the VibeMonitor bridge as a REST sensor.
sensor:
  - platform: rest
    name: VibeMonitor
    resource: {resource}
    headers:
      X-VibeMonitor-Token: "{token}"
    scan_interval: 10
    value_template: "{{{{ value_json.waiting_count }}}}"
    json_attributes:
      [claude_pct, codex_pct, claude_reset_min, waiting_count, working_count,
       any_waiting, longest_waiting_sec, capacity_status, stale_sec, waiting]

# Ready-made named entities derived from the REST sensor above.
template:
  - sensor:
      - name: Claude Usage
        unique_id: vibemonitor_claude_pct
        unit_of_measurement: "%"
        state: "{{{{ state_attr('sensor.vibemonitor', 'claude_pct') }}}}"
      - name: Codex Usage
        unique_id: vibemonitor_codex_pct
        unit_of_measurement: "%"
        state: "{{{{ state_attr('sensor.vibemonitor', 'codex_pct') }}}}"
      - name: VibeMonitor Waiting Count
        unique_id: vibemonitor_waiting_count
        state: "{{{{ state_attr('sensor.vibemonitor', 'waiting_count') }}}}"
  - binary_sensor:
      - name: VibeMonitor Needs Me
        unique_id: vibemonitor_needs_me
        device_class: problem
        state: "{{{{ state_attr('sensor.vibemonitor', 'any_waiting') | bool(false) }}}}"
      - name: VibeMonitor Bridge Online
        unique_id: vibemonitor_bridge_online
        device_class: connectivity
        state: >
          {{% set s = state_attr('sensor.vibemonitor', 'stale_sec') %}}
          {{{{ s is not none and s >= 0 and s < 30 }}}}
"""

    automation = """# configuration.yaml — react the instant a session needs you (webhook push).
# Set [homeassistant] webhook_url in config.toml to:
#   http://homeassistant.local:8123/api/webhook/vibemonitor-xxxxx
automation:
  - alias: VibeMonitor needs me
    trigger:
      - platform: webhook
        webhook_id: vibemonitor-xxxxx
        local_only: true
    action:
      - choose:
          - conditions: "{{ trigger.json.event == 'waiting' }}"
            sequence:
              - service: light.turn_on
                target: { entity_id: light.office }
                data: { rgb_color: [245, 166, 35] }   # amber
          - conditions: "{{ trigger.json.event == 'cleared' }}"
            sequence:
              - service: light.turn_off
                target: { entity_id: light.office }
"""
    return {"sensor": sensor, "automation": automation}


def _install_hooks_into_settings(token: str, url: str) -> dict:
    """Read ~/.claude/settings.json (or {}), merge our hooks, back up + write.
    Idempotent. Returns {"ok": bool, "message": str}. Mirrors install_hooks.main."""
    # install_hooks lives under bridge/hooks (not importable as a package), so add it.
    hooks_dir = Path(__file__).parent.parent / "hooks"
    if str(hooks_dir) not in sys.path:
        sys.path.insert(0, str(hooks_dir))
    import install_hooks  # noqa: E402

    settings_path = Path.home() / ".claude" / "settings.json"
    try:
        if settings_path.exists():
            settings = json.loads(settings_path.read_text(encoding="utf-8"))
            backup = settings_path.with_suffix(".json.vibemonitor.bak")
            shutil.copy(settings_path, backup)
        else:
            settings = {}
            settings_path.parent.mkdir(parents=True, exist_ok=True)
        command = install_hooks._our_command(hooks_dir, token, url)
        merged = install_hooks.merge_hooks(settings, command=command)
        settings_path.write_text(json.dumps(merged, indent=2), encoding="utf-8")
        return {"ok": True, "message": f"Installed hooks into {settings_path}"}
    except Exception as e:
        return {"ok": False, "message": f"Failed to install hooks: {e}"}


