_STATIC_DIR = Path(__file__).parent / "static"

# Where the bridge expects its config: bridge/config.toml (next to vibemonitor/).
DEFAULT_CONFIG_PATH = Path(__file__).parent.parent / "config.toml"

# Random-word pool for a friendly default ntfy topic suffix.
_TOPIC_WORDS = (
    "otter", "willow", "comet", "harbor", "lumen", "pixel", "ember", "cedar",
    "marble", "quartz", "nimbus", "fjord", "cobalt", "sprout", "thistle", "raven",
)

# Default thresholds — written verbatim so a fresh config has the documented values.
_DEFAULT_THRESHOLDS = {"working_sec": 60, "waiting_ttl_sec": 1800, "gone_ttl_sec": 14400}


# --------------------------------------------------------------------------- #
# TOML serialization (hand-rolled — stdlib has a reader but no writer).
# --------------------------------------------------------------------------- #

def _toml_value(v) -> str:
    """Serialize a scalar to TOML. Quote strings, lowercase booleans, pass numbers."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    # string: escape backslash and double-quote, emit a basic string
    s = str(v).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{s}"'


def _toml_inline_table(d: dict) -> str:
    """Serialize a flat dict as a TOML inline table: { k = v, ... }."""
    parts = [f"{k} = {_toml_value(v)}" for k, v in d.items()]
    return "{ " + ", ".join(parts) + " }"


def _b(form: dict, key: str, default: bool = False) -> bool:
    return bool(form.get(key, default))


def _s(form: dict, key: str) -> str | None:
    v = form.get(key)
    if v is None:
        return None
    v = str(v).strip()
    return v or None


def build_toml(form: dict) -> str:
    """Turn a settings dict into a valid config.toml string. Pure function.

    Recognized keys (all optional except `token`):
      token, host, port,
      enable_claude, enable_codex,
      summary_enabled, summary_model, summary_max_chars, openrouter_api_key,
      ha_webhook_url,
      push_provider, push_ntfy_url, push_pushover_token, push_pushover_user,
      push_escalate_sec,
      pricing  -> {model_id: {"input": float, "output": float}}

    Empty/disabled optional sections are omitted cleanly.
    """
    lines: list[str] = ["# VibeMonitor bridge configuration — generated by the setup wizard."]

    # ---- top level ----
    token = _s(form, "token") or secrets.token_urlsafe(12)
    lines.append(f"token = {_toml_value(token)}")
    lines.append(f"host = {_toml_value(_s(form, 'host') or '0.0.0.0')}")
    port = form.get("port", 5151)
    try:
        port = int(port)
    except (TypeError, ValueError):
        port = 5151
    lines.append(f"port = {port}")
    lines.append("")

    # ---- [thresholds] (defaults) ----
    lines.append("[thresholds]")
    for k, v in _DEFAULT_THRESHOLDS.items():
        lines.append(f"{k} = {v}")
    lines.append("")

    # ---- [poll] (defaults) ----
    lines.append("[poll]")
    lines.append("sessions_sec = 2.0")
    lines.append("usage_sec = 60.0")
    lines.append("costs_sec = 120.0")
    lines.append("summary_sec = 15.0")
    lines.append("")

    # ---- [providers] ----
    lines.append("[providers]")
    lines.append(f"claude = {_toml_value(_b(form, 'enable_claude', True))}")
    lines.append(f"codex = {_toml_value(_b(form, 'enable_codex', True))}")
    lines.append("")

    # ---- [summary] (only if enabled) ----
    if _b(form, "summary_enabled"):
        lines.append("[summary]")
        lines.append("enabled = true")
        model = _s(form, "summary_model") or "google/gemma-4-31b-it:free"
        lines.append(f"model = {_toml_value(model)}")
        max_chars = form.get("summary_max_chars", 2000)
        try:
            max_chars = int(max_chars)
        except (TypeError, ValueError):
            max_chars = 2000
        lines.append(f"max_chars = {max_chars}")
        lines.append("")

        api_key = _s(form, "openrouter_api_key")
        if api_key:
            lines.append("[openrouter]")
            lines.append(f"api_key = {_toml_value(api_key)}")
            lines.append("")

    # ---- [homeassistant] (only if a webhook url is set) ----
    ha_url = _s(form, "ha_webhook_url")
    if ha_url:
        lines.append("[homeassistant]")
        lines.append(f"webhook_url = {_toml_value(ha_url)}")
        lines.append("")

    # ---- [push] (only if configured for the selected provider) ----
    provider = (_s(form, "push_provider") or "ntfy").lower()
    ntfy_url = _s(form, "push_ntfy_url")
    po_token = _s(form, "push_pushover_token")
    po_user = _s(form, "push_pushover_user")
    push_configured = (provider == "ntfy" and ntfy_url) or (
        provider == "pushover" and po_token and po_user
    )
    if push_configured:
        lines.append("[push]")
        lines.append(f"provider = {_toml_value(provider)}")
        if provider == "ntfy":
            lines.append(f"ntfy_url = {_toml_value(ntfy_url)}")
        else:
            lines.append(f"pushover_token = {_toml_value(po_token)}")
            lines.append(f"pushover_user = {_toml_value(po_user)}")
        escalate = form.get("push_escalate_sec", 600)
        try:
            escalate = int(escalate)
        except (TypeError, ValueError):
            escalate = 600
        lines.append(f"escalate_sec = {escalate}")
        lines.append("")

    # ---- [pricing] (only if any rows) ----
    pricing = form.get("pricing")
    if isinstance(pricing, dict) and pricing:
        rows = {
            str(k): {"input": float(v["input"]), "output": float(v["output"])}
            for k, v in pricing.items()
            if isinstance(v, dict) and "input" in v and "output" in v
        }
        if rows:
            lines.append("[pricing]")
            for k, v in rows.items():
                lines.append(f"{_toml_value(k)} = {_toml_inline_table(v)}")
            lines.append("")

    return "\n".join(lines).rstrip() + "\n"


